/*
** EPITECH PROJECT, 2025
** mp3player
** File description:
** sound of the possible duplicates: the songs of the groups whose sound
** is not known yet are read one per tick (a file takes a fraction of a
** second to decode), then each song is compared to the reference of its
** group. A song whose sound differs leaves the group (two different
** songs with the same title); the groups are sorted, the surest first.
*/

#include "mp3player.h"

static void add_todo(app_t *app, dupscene_t *scene, song_t *song)
{
    for (int i = 0; i < scene->nb_todo; i++)
        if (scene->todo[i] == song)
            return;
    if (envelope_find(app->lib, song_hash(app->lib, song)))
        return;
    scene->todo[scene->nb_todo] = song;
    scene->nb_todo++;
}

int dupscene_todo(app_t *app)
{
    dupscene_t *scene = app->dupscene;
    dup_list_t *list = &scene->list;

    scene->todo = malloc(sizeof(song_t *) * (list->nb * DUP_GROUP_MAX + 1));
    if (!scene->todo)
        return 84;
    for (int g = 0; g < list->nb; g++)
        for (int i = 0; i < list->groups[g].nb; i++)
            add_todo(app, scene, list->groups[g].songs[i]);
    return 0;
}

/*
** the version generated by YouTube first, else the most listened one
*/
static void reference(library_t *lib, dup_group_t *group)
{
    int best = 0;
    song_t *swap = NULL;

    for (int i = 1; i < group->nb; i++) {
        if (group->songs[i]->autogen != group->songs[best]->autogen) {
            best = group->songs[i]->autogen ? i : best;
            continue;
        }
        if (song_total_listen(lib, group->songs[i])
            > song_total_listen(lib, group->songs[best]))
            best = i;
    }
    swap = group->songs[0];
    group->songs[0] = group->songs[best];
    group->songs[best] = swap;
}

static void compare_group(library_t *lib, dup_group_t *group)
{
    envelope_t *ref = NULL;
    envelope_t *other = NULL;

    reference(lib, group);
    ref = song_envelope(lib, group->songs[0]);
    group->audio[0] = 100;
    for (int i = group->nb - 1; i > 0; i--) {
        other = song_envelope(lib, group->songs[i]);
        group->audio[i] = -1;
        if (ref && other && ref->nb > 0 && other->nb > 0)
            group->audio[i] = envelope_compare(ref, other);
        if (group->audio[i] >= 0 && group->audio[i] < DUP_DIFFERENT)
            dup_group_remove(group, i);
    }
}

static void finish(app_t *app, dupscene_t *scene)
{
    for (int g = 0; g < scene->list.nb; g++)
        compare_group(app->lib, &scene->list.groups[g]);
    scene->auto_merged = dup_auto_merge(app);
    dupscene_clean(app);
    scene->ready = 1;
}

void dupscene_update(app_t *app)
{
    dupscene_t *scene = app->dupscene;

    if (scene->ready)
        return;
    if (scene->done < scene->nb_todo) {
        song_envelope(app->lib, scene->todo[scene->done]);
        scene->done++;
        return;
    }
    finish(app, scene);
}
